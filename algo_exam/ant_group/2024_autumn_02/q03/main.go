// 题意摘要：小红有一个一维的坐标系,上面一共有 n 个点,依次为 1,2,...,n ,她初始时位于 k 。现在她按照一个指令集合运动,如下: ● 指令 L : 向左移动一个单位,如果当前位于 1 ,则原地不动。 ● 指令 R : 向右移动一个单位,如果当前位于 n ,则原地不动。 ● 指令 ? : 未知,小红将随机移动 L 或者 R 。 在经过所有指令运动后,小红想知道哪些位置有可能成为终点。如果该点可能成为终点,输出 1 ,否则输出 0 。
// 输入：第一行输入两个整数 n,k(1 ≤ n ≤ 10^5; 1 ≤ k ≤ n) ,分别表示坐标系长度和小红的初始位置。 第二行输入一个长度不超过 10^5 、且仅由 L 、R 和 ? 构成的字符串 s ,表示移动的指令集。
// 输出：在一行上输出 n 个数字 a_1,a_2,...,a_n( 0≤ a_i ≤ 1 ) 代表每一个点是否可能成为小红的终点。
// 时间限制：1 秒；其他语言 2 秒
