// 题意摘要：有一个 n 行 n 列的棋盘,每个格子上写着数字 0 或 1 。有一个小球从某个格子出发,移动到写着 0 的格子时会向下移动一格;移动到写着 1 的格子时会向右移动一格,直到滚出棋盘边界。 现在有q个询问,每次询问在子矩阵 (x_1,y_1)~(x_2,y_2) 中,小球从 (x_1,y_1) 出发开始滚动,最后会从哪个格子滚出子矩阵 (x_1,y_1)~(x_2,y_2) 。 从某个格子滚出子矩阵(x_1,y_1)~(x_2,y_2) ,意思是当前所在的格子在子矩阵内,但是小球滚动路径的下一个格子不在子矩阵内,视为滚出。 从棋盘 (x,y) 向右滚动一格即抵达 (x,y+1) ,从棋盘 (x,y) 向下滚动一格即抵达 (x+1,y) 。
// 输入：第一行输入一个整数 n( 1 ≤ n ≤ 500) 代表棋盘大小。 此后 n 行,每行输入 n 个整数 a_1,a_2,...,a_n( 0≤ a_i≤ 1) 代表棋盘上每个格子上写的数字。 第 n+2 行输入一个整数 q (1≤ q ≤ 2× 10^5 ) 代表询问次数。 随后 q 行,每行输入四个整数 x_1,y_1,x_2,y_2(1 ≤ x_1, x_2 , y_1, y_2 ≤ n ; x_1 ≤ x_2; y_1 ≤ y_2) 代表子矩阵范围。
// 输出：对于每一次询问,在一行上输出两个整数,代表小球滚出的位置。
// 时间限制：3 秒；其他语言 6 秒
// 空间限制：256 MB；其他语言 512 MB
//
