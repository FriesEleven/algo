// 输入：第一行有两个整数 n,k(1 ≤ n ≤ 500 , 1 ≤ k ≤ 26),分别代表小明的字符串长度与字符串中的字符种类数(保证 n 为偶数且串的内容仅由前 k 个小写英文字母组成)。 接下来 k 行给出了一个 k × k 的由整数构成的矩阵。 矩阵中第 i 行第 j 列的元素代表消除相邻的第 i 个字母和第 j 个字母所能花掉的钱数。 最后一行有一个长度为 n 的字符串,代表小明的字符串。
// 输出：输出一个值,代表小亮最多能花掉小明多少零花钱。
