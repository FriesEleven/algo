// 题意摘要：小苯是“小红书app”的一名博主,这天他想要给自己的“铁粉”送一些礼物。 他有 n 名粉丝,编号从 1 到 n,但他只能选择其中 k 名送礼物,他决定选择其中对他支持力度最大的前 k 名粉丝。 (如果两名支持力度相同,则优先选择收藏数更多的,如果都一样,则优先选择编号更小的(因为这意味着他关注小苯的时间更早)) 具体的:每名粉丝如果每给小苯点一次赞,则他对小苯就增加了 1 点支持力度,如果他每收藏小苯的一篇文章,则他对小苯增加 2 点支持力度。 现在小苯想知道,他应该选择哪 k 名粉丝送出礼物,请你帮帮他吧。
// 输入：输入包含 n+1行。 第一行两个正整数 n, k (1 ≤ k ≤ n ≤ 10^5),分别表示对小苯有过支持的粉丝个数,以及小苯选择送礼的粉丝个数。 接下来 n 行,每行两个整数 x_i, y_i (0 ≤ x_i, y_i ≤ 10^5),表示第 i 位粉丝给小苯点过 x 次赞,收藏过 y 个小苯的文章。
