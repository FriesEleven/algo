// 题目：单层 GRU的隐藏状态
// 试卷：2026年春招-美团-算法策略岗-第二批笔试
// 题目直链：https://www.nowcoder.com/questionTerminal/cf751582944e4161ae235af510e1af36
//
// 题意摘要：给定输入序列 x_1...x_T、GRU 权重与偏置以及初始隐藏状态 h_0，计算最终隐藏状态 h_T。
//   对每个时刻 t，重置门 r_t = σ(x_t W_xr + h_(t-1) W_hr + b_r)。
//   更新门 z_t = σ(x_t W_xz + h_(t-1) W_hz + b_z)。
//   候选状态 h~_t = tanh(x_t W_xh + (r_t ⊙ h_(t-1)) W_hh + b_h)。
//   当前状态 h_t = (1-z_t) ⊙ h_(t-1) + z_t ⊙ h~_t。
//   其中 σ(x)=1/(1+e^(-x))，⊙ 表示逐元素乘；权重按 r、z、h 三部分列拼接。
//   只需进行前向传播，所有运算使用 float64，结果四舍五入保留 6 位小数。
// 输入：单行 JSON,字段: { "Wx": [[...], ...], // d × 3h "Wh": [[...], ...], // h × 3h "b": [...], // 长度 3h "h0": [...], // 长度 h "X": [[...], ...] // T × d (按时间顺序) } • d,h,T 皆 ≤ 3 • 所有值为数值;不含缺失 • "Wx":二维数组,形状 [d,3h]。即[W_{xr} | W_{xz} | W_{xh}]。 • "Wh":二维数组,形状 [h,3h]。即 [W_{hr} | W_{hz} | W_{hh}]。 • "b":一维数组,长度 3h。依次对应[b_r, b_z, b_h]。 • "h0":一维数组,长度 h。初始隐藏状态 h_0。 • "X":二维数组,形状 [T,d]。按时间顺序存放各步输入x_t;即第 t 行就是x_t。
// 输出：仅一行: [hT_1, hT_2, ...] // 长度 = h 每元素保留 6 位小数(使用round(x,6)即可),顺序与隐藏维度一致。
// 时间限制：5 秒；其他语言 10 秒
// 空间限制：256 MB；其他语言 512 MB
//
