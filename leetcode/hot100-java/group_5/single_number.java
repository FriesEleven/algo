/*
只出现一次的数字

给定非空整数数组 nums，除某个元素只出现一次外，其余每个元素都恰好出现两次。找出只
出现一次的元素；要求线性时间且不使用额外存储空间。

算法实现说明：
1. 异或有三个有用性质：相同数字异或得到 0，任何数字与 0 异或仍是自己，而且运算顺序
   可以任意交换。
2. `unique` 从 0 开始，依次和数组中的每个数字做异或。
3. 所有出现两次的数字无论位于哪里，最终都会两两抵消成 0；只有出现一次的数字没有配对，
   会保留在结果中。
4. 整个过程只使用一个整数变量，满足不能使用额外存储空间的要求。

时间复杂度 O(n)，空间复杂度 O(1)。
*/
class Solution {
    public int singleNumber(int[] nums) {
        int unique = 0;
        for (int number : nums) {
            unique ^= number;
        }
        return unique;
    }
}
